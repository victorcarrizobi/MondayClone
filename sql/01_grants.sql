-- ============================================================
-- 01_grants.sql  --  Grant ATTENDEE_ROLE access to FINSERV_DW
-- ============================================================
-- These must be run by ACCOUNTADMIN (or a role with MANAGE GRANTS).
-- ATTENDEE_ROLE already has MANAGE GRANTS, so it can self-grant.
-- Dynamic Tables need explicit USAGE + SELECT, not just inherited access.

USE ROLE ATTENDEE_ROLE;

-- Database-level USAGE
GRANT USAGE ON DATABASE FINSERV_DW TO ROLE ATTENDEE_ROLE;

-- Schema-level USAGE
GRANT USAGE ON SCHEMA FINSERV_DW.CORE        TO ROLE ATTENDEE_ROLE;
GRANT USAGE ON SCHEMA FINSERV_DW.RISK         TO ROLE ATTENDEE_ROLE;
GRANT USAGE ON SCHEMA FINSERV_DW.INSURANCE    TO ROLE ATTENDEE_ROLE;
GRANT USAGE ON SCHEMA FINSERV_DW.ANALYTICS    TO ROLE ATTENDEE_ROLE;
GRANT USAGE ON SCHEMA FINSERV_DW.TRANSACTIONS TO ROLE ATTENDEE_ROLE;

-- Table-level SELECT (all tables we reference)
GRANT SELECT ON TABLE FINSERV_DW.CORE.CUSTOMERS           TO ROLE ATTENDEE_ROLE;
GRANT SELECT ON TABLE FINSERV_DW.CORE.ACCOUNTS             TO ROLE ATTENDEE_ROLE;
GRANT SELECT ON TABLE FINSERV_DW.RISK.FRAUD_ALERTS         TO ROLE ATTENDEE_ROLE;
GRANT SELECT ON TABLE FINSERV_DW.RISK.RISK_ASSESSMENTS     TO ROLE ATTENDEE_ROLE;
GRANT SELECT ON TABLE FINSERV_DW.INSURANCE.CLAIMS          TO ROLE ATTENDEE_ROLE;

-- View-level SELECT
GRANT SELECT ON VIEW FINSERV_DW.ANALYTICS.CUSTOMER_360     TO ROLE ATTENDEE_ROLE;
